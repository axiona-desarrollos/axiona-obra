const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const errores = [];
  const cel = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1080 / 390, isMobile: true, hasTouch: true, locale: 'es-CO' });
  const p = await cel.newPage();
  p.on('pageerror', e => errores.push('cel: ' + e.message));
  await p.goto('http://localhost:8171/', { waitUntil: 'networkidle' });
  await p.screenshot({ path: 'tomas/topo-inicio.png' });
  await p.click('[data-act="ejemplo"]');
  await p.click('.dock [data-vista="plano"]');
  await p.waitForTimeout(500);
  await p.screenshot({ path: 'tomas/topo-plano.png' });
  await p.click('.dock [data-vista="holo"]');
  await p.waitForTimeout(3000);
  await p.screenshot({ path: 'tomas/topo-holo.png' });
  await p.click('[data-act="rayos"]');
  await p.waitForTimeout(3000);
  await p.screenshot({ path: 'tomas/topo-rayos.png' });
  await p.click('#v-holo [data-act="huella"]');
  await p.click('[data-act="exag"][data-k="5"]');
  await p.waitForTimeout(3000);
  await p.screenshot({ path: 'tomas/topo-rayos-x5.png' });
  const pc = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1.5, locale: 'es-CO' });
  const q = await pc.newPage();
  q.on('pageerror', e => errores.push('pc: ' + e.message));
  await q.goto('http://localhost:8171/', { waitUntil: 'networkidle' });
  await q.click('.intro [data-act="ejemplo"]');
  await q.click('.dock [data-vista="holo"]');
  await q.waitForTimeout(3000);
  await q.click('[data-act="rayos"]');
  await q.waitForTimeout(3000);
  await q.screenshot({ path: 'tomas/pc-holo.png' });
  console.log('ERRORES', errores.length ? errores.join('\n') : 'ninguno');
  await b.close();
})();
